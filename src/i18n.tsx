export type TKey = keyof (typeof dict)['en']

export const LANGS: { code: Lang; label: string }[] = [
  { code: 'en', label: 'EN' },
  { code: 'ar', label: 'عربي' },
  { code: 'ku', label: 'کوردی' },
]

const RTL: Lang[] = ['ar', 'ku']

const LangContext = createContext<{
  lang: Lang
  setLang: (l: Lang) => void
  t: (k: TKey) => string
}>({ lang: 'en', setLang: () => {}, t: (k) => dict.en[k] }) // English, never the raw key (a stale HMR context once showed keys)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const saved = localStorage.getItem('mars-lang')
    return saved === 'ar' || saved === 'ku' || saved === 'en' ? saved : 'en'
  })

  useEffect(() => {
    localStorage.setItem('mars-lang', lang)
    document.documentElement.lang = lang
    document.documentElement.dir = RTL.includes(lang) ? 'rtl' : 'ltr'
  }, [lang])

  const t = (k: TKey) => dict[lang][k]
  return (
    <LangContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LangContext.Provider>
  )
}

export const useLang = () => useContext(LangContext)
